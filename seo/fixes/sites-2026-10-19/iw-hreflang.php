add_action( 'wp_head', function () {
	if ( is_admin() || is_paged() || is_search() || is_404() ) {
		return;
	}
	$path = (string) wp_parse_url( (string) ( $_SERVER['REQUEST_URI'] ?? '/' ), PHP_URL_PATH );
	$path = '/' . trim( $path, '/' ) . ( '/' === $path ? '' : '/' );
	$path = '//' === $path ? '/' : $path;
	if ( ! isset( IW_HREFLANG_MAP[ $path ] ) ) {
		return;
	}
	$sites = explode( ',', IW_HREFLANG_MAP[ $path ] );
	$langs = array( 'eu' => array( 'en-GB', 'en-IE' ), 'com' => array( 'en-US' ), 'au' => array( 'en-AU' ) );
	foreach ( $sites as $s ) {
		foreach ( $langs[ $s ] as $l ) {
			echo '<link rel="alternate" hreflang="' . esc_attr( $l ) . '" href="' . esc_url( IW_HREFLANG_HOSTS[ $s ] . $path ) . '">' . "\n";
		}
	}
	$default = in_array( 'eu', $sites, true ) ? 'eu' : $sites[0];
	echo '<link rel="alternate" hreflang="x-default" href="' . esc_url( IW_HREFLANG_HOSTS[ $default ] . $path ) . '">' . "\n";
}, 2 );
